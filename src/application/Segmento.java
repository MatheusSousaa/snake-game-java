package application;

public class Segmento {

    private int segX;
    private int segY;

    public Segmento(int segX, int segY) {
        this.segX = segX;
        this.segY = segY;
    }

    public int getSegX() {
        return segX;
    }
    public void setSegX(int segX) {
        this.segX = segX;
    }
    public int getSegY() {
        return segY;
    }
    public void setSegY(int segY) {
        this.segY = segY;
    }
}
